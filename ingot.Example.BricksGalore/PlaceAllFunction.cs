using System.Text;

using ingot.Core;

namespace ingot.Example.BricksGalore;

/// <summary>
/// Writes .mcfunction files that place / clear every Bricks Galore block in a gallery grid.
/// </summary>
public static class PlaceAllFunction
{
    public const string PlaceFunctionName = "place_all";
    public const string ClearFunctionName = "clear_all";

    /// <summary>Legacy alias for <see cref="PlaceFunctionName"/>.</summary>
    public const string FunctionName = PlaceFunctionName;

    /// <summary>
    /// Layout (relative to the execution origin):
    /// <list type="bullet">
    /// <item><b>X</b> - body groups; each group is plain then overlay columns</item>
    /// <item><b>Z</b> - pattern (one row per pattern)</item>
    /// <item><b>Y</b> - same height as origin</item>
    /// </list>
    /// One empty column between body groups.
    /// </summary>
    public static (string PlacePath, string ClearPath) Generate(string functionsDir)
    {
        string[] materials = BrickStats.Materials;
        string[] patterns = BrickStats.PatternIds;
        int matCount = materials.Length;

        // group width: 1 plain + matCount overlays + 1 gap (gap omitted after last group)
        int groupStride = 1 + matCount + 1;
        int maxX = matCount * groupStride - 2;
        int maxZ = patterns.Length - 1;

        StringBuilder place = new();
        place.AppendLine("# autogenerated by ingot.Example.BricksGalore - do not edit");
        place.AppendLine("# places every pack block in a grid relative to the execution origin (~ ~ ~).");
        place.AppendLine("#");
        AppendLayoutComments(place, materials, patterns, matCount);
        place.AppendLine("# usage: stand at the nw corner of the gallery, then");
        place.AppendLine($"#   /function {PlaceFunctionName}");
        place.AppendLine("# clear with the same origin:");
        place.AppendLine($"#   /function {ClearFunctionName}");
        place.AppendLine();

        StringBuilder clear = new();
        clear.AppendLine("# autogenerated by ingot.Example.BricksGalore - do not edit");
        clear.AppendLine("# removes the place_all gallery relative to the execution origin (~ ~ ~).");
        clear.AppendLine("# stand at the same nw corner used for /function place_all.");
        clear.AppendLine("#");
        AppendLayoutComments(clear, materials, patterns, matCount);
        clear.AppendLine($"# usage: /function {ClearFunctionName}");
        clear.AppendLine();

        // single fill covers blocks and gaps between body groups.
        clear.AppendLine($"# fill entire gallery footprint with air ({maxX + 1} x 1 x {maxZ + 1})");
        clear.AppendLine($"fill ~0 ~ ~0 ~{maxX} ~ ~{maxZ} air");
        clear.AppendLine();

        int placed = 0;
        for (int zi = 0; zi < patterns.Length; zi++)
        {
            string pattern = patterns[zi];
            place.AppendLine($"# --- {pattern} (z={zi}) ---");

            for (int bi = 0; bi < matCount; bi++)
            {
                string body = materials[bi];
                int groupStart = bi * groupStride;

                // column 0: plain (no inlay) - original base texture recoloured.
                {
                    string plain = BrickStats.BlockName(body, pattern, overlayMaterial: null);
                    place.AppendLine($"setblock ~{groupStart} ~ ~{zi} {BrickStats.Namespace}:{plain}");
                    placed++;
                }

                if (!BrickStats.HasOverlay(pattern))
                    continue;

                // columns 1..matCount: overlay variants
                for (int oi = 0; oi < matCount; oi++)
                {
                    string overlay = materials[oi];
                    string name = BrickStats.BlockName(body, pattern, overlay);
                    int x = groupStart + 1 + oi;
                    place.AppendLine($"setblock ~{x} ~ ~{zi} {BrickStats.Namespace}:{name}");
                    placed++;
                }
            }

            place.AppendLine();
        }

        place.AppendLine($"# total blocks placed: {placed}");
        place.AppendLine($"tellraw @s {{\"rawtext\":[{{\"text\":\"§aBricks Galore: placed {placed} blocks\"}}]}}");

        clear.AppendLine($"# total cells cleared: {(maxX + 1) * (maxZ + 1)} (includes 1-block gaps)");
        clear.AppendLine($"tellraw @s {{\"rawtext\":[{{\"text\":\"§cBricks Galore: cleared gallery ({maxX + 1}x{maxZ + 1})\"}}]}}");

        Directory.CreateDirectory(functionsDir);
        string placePath = Path.Combine(functionsDir, $"{PlaceFunctionName}.mcfunction");
        string clearPath = Path.Combine(functionsDir, $"{ClearFunctionName}.mcfunction");
        File.WriteAllText(placePath, place.ToString());
        File.WriteAllText(clearPath, clear.ToString());

        CompilerState.Info($"wrote {PlaceFunctionName}.mcfunction ({placed} setblocks) -> {placePath}");
        CompilerState.Info($"wrote {ClearFunctionName}.mcfunction (fill ~0 ~0 ~0 ~{maxX} ~ ~{maxZ} air) -> {clearPath}");
        return (placePath, clearPath);
    }

    private static void AppendLayoutComments(
        StringBuilder sb,
        string[] materials,
        string[] patterns,
        int matCount)
    {
        sb.AppendLine("# layout:");
        sb.AppendLine("#   z = pattern (one row each)");
        sb.AppendLine("#   x = body groups: [plain] [overlay x materials] [gap]");
        sb.AppendLine("#");
        sb.AppendLine($"# materials ({matCount}): {string.Join(", ", materials)}");
        sb.AppendLine($"# patterns ({patterns.Length}): {string.Join(", ", patterns)}");
        sb.AppendLine("#");
    }
}
