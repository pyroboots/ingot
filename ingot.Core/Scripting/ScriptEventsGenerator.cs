using System.Text;

using ingot.Core.Common;

namespace ingot.Core.Scripting;

/// <summary>
/// Generates Script API custom component registration scripts.
/// </summary>
internal static class ScriptEventsGenerator
{
    /// <summary>
    /// Generates the JSON component name and JavaScript source for the given bindings.
    /// </summary>
    public static (string jsonComponentName, string code) Generate(Identifier id, IScriptEvents events)
    {
        StringBuilder sb = new();
        sb.AppendLine("// autogenerated by ingot");
        sb.AppendLine();
        sb.AppendLine("import { system } from \"@minecraft/server\";");

        // Extra Script API modules (e.g. @minecraft/server-ui) are imported as namespaces
        // so handler bodies can reference them, e.g. `new serverUi.MessageFormData()`.
        foreach (string module in CompilerState.CurrentPack!.ScriptApiModules.Keys)
        {
            if (module == "@minecraft/server") continue;
            sb.AppendLine($"import * as {ModuleImportAlias(module)} from \"{module}\";");
        }

        sb.AppendLine();

        List<(string EventName, string Body)> resolved = [];
        List<string> hoistedImports = [];
        foreach (ScriptEventBinding binding in events.Bindings)
        {
            (IReadOnlyList<string> imports, string body) = ScriptImportHoist.Split(binding.Handler.ResolveBody());
            hoistedImports.AddRange(imports);
            resolved.Add((binding.ScriptApiEvent, body));
        }

        foreach (string import in hoistedImports.Distinct(StringComparer.Ordinal))
            sb.AppendLine(import);
        if (hoistedImports.Count > 0)
            sb.AppendLine();

        string suffix = events.ComponentKind == ScriptComponentKind.Block
            ? "block_events_component"
            : "item_events_component";

        string codeComponentName = Formatting.SnakeToPascalCase(string.Join('_', [
            id.Namespace,
            id.Name,
            suffix,
        ]));
        string jsonComponentName = $"{id.Namespace}:" + Formatting.PascalToSnakeCase(codeComponentName);

        sb.AppendLine($"const {codeComponentName} = {{");

        foreach ((string eventName, string body) in resolved)
            sb.AppendLine(ComponentEvent(eventName, body));

        sb.AppendLine("};");
        sb.AppendLine();

        string registryName = events.ComponentKind == ScriptComponentKind.Block
            ? "blockComponentRegistry"
            : "itemComponentRegistry";

        sb.AppendLine("system.beforeEvents.startup.subscribe(({ " + registryName + " }) => {");
        sb.AppendLine($"    {registryName}.registerCustomComponent(");
        sb.AppendLine($"        \"{jsonComponentName}\",");
        sb.AppendLine($"        {codeComponentName}");
        sb.AppendLine("    );");
        sb.AppendLine("});");

        return (jsonComponentName, sb.ToString());
    }

    /// <summary>
    /// Builds a JS identifier for a module import, e.g. <c>@minecraft/server-ui</c> → <c>serverUi</c>.
    /// </summary>
    internal static string ModuleImportAlias(string moduleName)
    {
        string name = moduleName;
        int slash = name.LastIndexOf('/');
        if (slash >= 0 && slash < name.Length - 1)
            name = name[(slash + 1)..];

        string[] parts = name.Split('-', StringSplitOptions.RemoveEmptyEntries);
        if (parts.Length == 0)
            return "mod";

        string alias = parts[0];
        for (int i = 1; i < parts.Length; i++)
        {
            string part = parts[i];
            if (part.Length == 0) continue;
            alias += char.ToUpperInvariant(part[0]) + part[1..];
        }

        return alias;
    }

    /// <summary>
    /// Builds the JSON component name for the given identifier and component kind.
    /// </summary>
    public static string GetJsonComponentName(Identifier id, ScriptComponentKind kind)
    {
        string suffix = kind == ScriptComponentKind.Block
            ? "block_events_component"
            : "item_events_component";

        string codeComponentName = Formatting.SnakeToPascalCase(string.Join('_', [
            id.Namespace,
            id.Name,
            suffix,
        ]));

        return $"{id.Namespace}:" + Formatting.PascalToSnakeCase(codeComponentName);
    }

    private static string ComponentEvent(string name, string content)
    {
        StringBuilder sb = new();
        sb.Append(name);
        sb.AppendLine("(event) {");
        sb.AppendLine(content);
        sb.AppendLine("},");
        return sb.ToString();
    }
}