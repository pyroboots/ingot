using System.Text;

namespace ingot.Core.Scripting;

/// <summary>
/// Wraps script-event handler bodies in a Script API <c>scriptEventReceive</c> subscription.
/// </summary>
internal static class ScriptEventGenerator
{
    /// <summary>
    /// Generates a script that invokes <paramref name="body"/> when
    /// <c>/scriptevent <paramref name="eventId"/></c> is received.
    /// </summary>
    /// <param name="eventId">Full script event id (<c>namespace:name</c>).</param>
    /// <param name="body">Handler body; <c>event</c> is in scope.</param>
    public static string Generate(string eventId, string body)
    {
        (IReadOnlyList<string> imports, string handlerBody) = ScriptImportHoist.Split(body);

        StringBuilder sb = new();
        sb.AppendLine("// autogenerated by ingot");
        sb.AppendLine();
        sb.AppendLine("import { system, world } from \"@minecraft/server\";");
        foreach (string import in imports)
            sb.AppendLine(import);
        sb.AppendLine();
        sb.AppendLine("system.afterEvents.scriptEventReceive.subscribe((event) => {");
        sb.AppendLine($"    if (event.id !== \"{EscapeJsString(eventId)}\") return;");
        sb.AppendLine(handlerBody);
        sb.AppendLine("});");
        return sb.ToString();
    }

    private static string EscapeJsString(string value) =>
        value.Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal);
}
